import { expect, test } from "@playwright/test";
test("registra, persiste y compara tres escenarios con evidencia exportable",async({page,request})=>{
  const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/");
  await expect(page.getByRole("heading",{name:"Conozcamos tu finca"})).toBeVisible();
  await page.getByLabel("Nombre de la finca").fill("Finca E2E hipotética");
  await page.getByLabel("Latitud (° WGS84)").fill("10.19");
  await page.getByLabel("Longitud (° WGS84)").fill("-84.39");
  await page.getByLabel("Fuente o responsable").fill("Prueba automatizada hipotética");
  await page.getByLabel("Este registro es hipotético").check();
  await page.getByRole("button",{name:"Guardar finca",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Finca guardada");
  await page.getByRole("button",{name:"Registrar parcela"}).click();
  await page.getByLabel("Nombre de la parcela").fill("Parcela E2E");
  await page.getByLabel("Superficie",{exact:true}).fill("1.25");
  await page.getByLabel("Fuente o responsable").fill("Prueba de superficie declarada");
  await page.getByLabel("Este registro es hipotético").check();
  await page.getByRole("button",{name:"Guardar parcela",exact:true}).click();
  await expect(page.getByRole("status")).toContainText("Parcela guardada");
  await page.reload();
  await expect(page.getByRole("heading",{name:"Finca E2E hipotética"})).toBeVisible();
  await page.getByRole("button",{name:"Abrir parcela"}).click();
  await page.getByLabel("Fecha del muestreo o mapa").fill("2025-01-01");
  await page.getByLabel("Profundidad inicial (cm)").fill("0");
  await page.getByLabel("Profundidad final (cm)").fill("20");
  await page.getByLabel("pH",{exact:true}).fill("5.8");
  await page.getByLabel("Método del pH").fill("Método sintético de prueba");
  await page.getByLabel("Fuente o responsable").fill("Informe hipotético E2E");
  await page.getByLabel("Este registro es hipotético").check();
  await page.getByRole("button",{name:"Guardar registro de suelo"}).click();
  await expect(page.getByRole("status")).toContainText("Registro de suelo guardado");
  await page.getByRole("button",{name:"Comparar rotaciones"}).click();
  await expect(page.getByRole("button",{name:"Comparar las tres"})).toBeDisabled();
  for(let slot=1;slot<=3;slot++){
    const editor=page.locator(".scenario-editor").nth(slot-1);
    await editor.getByLabel("Inicio 1",{exact:true}).fill("2027-01-01");
    await editor.getByLabel("Fin 1",{exact:true}).fill("2027-03-01");
    await editor.getByRole("button",{name:"Añadir cultivo"}).click();
    await editor.getByLabel("Inicio 2",{exact:true}).fill(slot===2?"2027-02-01":"2027-03-02");
    await editor.getByLabel("Fin 2",{exact:true}).fill("2027-06-01");
    await editor.getByLabel("Fuente o responsable").fill("Escenario hipotético para prueba");
    await editor.getByLabel("Este registro es hipotético").check();
    await editor.getByRole("button",{name:`Guardar escenario ${slot}`}).click();
    await expect(page.getByRole("status")).toContainText(`Escenario ${slot} guardado`);
  }
  await page.getByRole("button",{name:"Comparar las tres"}).click();
  await expect(page.getByRole("heading",{name:"Evidencia reproducible"})).toBeVisible();
  await expect(page.locator(".status-UNKNOWN")).toHaveCount(15);
  await expect(page.locator(".status-FAIL")).toHaveCount(1);
  await expect(page.getByRole("heading",{name:"¿Qué información falta?"})).toBeVisible();
  await page.getByLabel("Variable").selectOption("irrigationRequired");
  await page.getByLabel("Nuevo valor").selectOption("yes");
  await page.getByRole("button",{name:"Comparar cambio hipotético"}).click();
  await expect(page.getByText("Hipotético.",{exact:false})).toBeVisible();
  const download=page.waitForEvent("download");
  await page.getByRole("button",{name:"Descargar evidencia JSON"}).click();
  const evidence=await download;
  expect(evidence.suggestedFilename()).toMatch(/^sueloruta-.*\.json$/);
  await evidence.saveAs("test-results/evidence.json");
  await page.screenshot({path:"test-results/comparison-desktop.png",fullPage:true});
  await page.reload();
  await page.getByRole("button",{name:"Evidencia y trazabilidad"}).click();
  await page.getByRole("button",{name:"Abrir evaluación"}).click();
  await expect(page.getByRole("heading",{name:"Evidencia reproducible"})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:"test-results/comparison-mobile.png",fullPage:true});
  const invalid=await request.post("/api/farms",{data:{name:"inválida"}});expect(invalid.status()).toBe(400);
  expect(errors).toEqual([]);
});
test("muestra fallos de conexión del clima sin fabricar resultados",async({page,request})=>{
  const farm=await request.post("/api/farms",{data:{name:"Finca climática de prueba",coordinates:{latitude:10.19,longitude:-84.39},resources:{irrigation:null,labor:null,equipment:null,budget:null},priorities:[],provenance:{kind:"DECLARED",source:"Fixture hipotético de Playwright",method:"Prueba E2E",date:"2025-01-01",resolution:null,assumptions:[],hypothetical:true}}});
  expect(farm.ok()).toBe(true);
  await page.goto("/");
  await page.getByRole("button",{name:"Clima histórico"}).click();
  await page.route("**/api/climate",route=>route.fulfill({status:502,contentType:"application/json",body:JSON.stringify({error:"No fue posible conectar con NASA POWER"})}));
  await page.getByLabel("Inicio de la consulta histórica").fill("2025-01-01");
  await page.getByLabel("Fin de la consulta histórica").fill("2025-01-03");
  await page.getByRole("button",{name:"Consultar NASA POWER"}).click();
  await expect(page.locator(".error[role=alert]")).toContainText("No fue posible conectar");
  await expect(page.getByText("días con datos")).toHaveCount(0);
});
